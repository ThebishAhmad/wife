-- Keep-Alive table recommended by travisvn/supabase-pause-prevention
CREATE TABLE IF NOT EXISTS public."keep-alive" (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NULL DEFAULT '',
  random UUID NULL DEFAULT gen_random_uuid(),
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- Enable Row Level Security
ALTER TABLE public."keep-alive" ENABLE ROW LEVEL SECURITY;

-- Allow read access for keep-alive ping verification
CREATE POLICY "Allow public read for keep-alive ping"
  ON public."keep-alive" FOR SELECT
  USING (true);

